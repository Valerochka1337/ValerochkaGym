package com.valerochka1337.valerochkagym.domain.analysis

/**
 * Оценка одноповторного максимума (e1RM) — общая «валюта» силы, в которой сравнимы подходы
 * с разным весом и числом повторений: 100 кг × 5 и 110 кг × 3 иначе не сопоставить, а именно
 * это нужно графику прогресса.
 *
 * Используется формула Эпли: `1RM = w × (1 + reps / 30)`. Она — самая обкатанная в
 * валидационных работах и практически не расходится с формулой Бжицки в рабочем диапазоне;
 * расхождения начинаются на больших числах повторений, где оценка и так теряет смысл.
 *
 * [MAX_TRUSTED_REPS] = 12: выше этого числа повторений оценка систематически завышает
 * максимум (усталость и техника перестают линейно зависеть от веса), поэтому такие подходы
 * в силовые метрики не идут вообще — лучше пропуск, чем красивый неверный рекорд.
 */
object OneRepMax {

    /** Максимум повторений, при котором оценке ещё можно верить. */
    const val MAX_TRUSTED_REPS: Int = 12

    /**
     * e1RM подхода или `null`, если оценивать нечего: нет веса/повторений, вес неположительный
     * или повторений больше [MAX_TRUSTED_REPS]. Один повтор — это сам вес, без наценки.
     */
    fun epley(weightKg: Double?, reps: Int?): Double? {
        if (weightKg == null || reps == null) return null
        if (weightKg <= 0.0 || reps < 1 || reps > MAX_TRUSTED_REPS) return null
        return if (reps == 1) weightKg else weightKg * (1.0 + reps / 30.0)
    }
}
