package com.valerochka1337.valerochkagym.ui.analysis.body

import com.valerochka1337.valerochkagym.data.db.entity.Muscle

/** Какую сторону тела показываем. */
enum class BodyView { FRONT, BACK }

/** Область карты тела: одна мышца и её фигуры (обычно левая и правая, иногда несколько пучков). */
data class BodyRegion(
    val muscle: Muscle,
    val shapes: List<BodyShape>,
)

/**
 * Геометрия интерактивной карты тела: силуэт и области мышц в нормированных координатах
 * 100 x 220 (ось Y вниз). Рисуется в Compose Canvas, поэтому никаких SVG- и растровых
 * ресурсов — только координаты: они масштабируются под любой размер без потери резкости
 * и одновременно служат для попадания тапа.
 *
 * Каждая фигура — замкнутый сплайн через опорные точки ([BodyShape]), а не ломаная: тело
 * состоит из округлых форм, и на карте размером с ладонь ломаная читается как «сломанная
 * картинка», а не как мышца. Опорных точек у каждой мышцы — восемь-десять, поэтому форму
 * видно прямо в тексте и её можно править по одному числу.
 *
 * Свойства, на которые опирается остальной код:
 *
 * * силуэт симметричен по построению — задаётся половина контура, вторая достраивается
 *   зеркально, и оба вида используют один и тот же силуэт, поэтому фигуры спереди и сзади
 *   стоят рядом одинаковыми;
 * * парные мышцы тоже задаются один раз и зеркалятся;
 * * области одного вида не пересекаются — иначе тап попадал бы в две мышцы сразу;
 * * между соседними областями оставлен зазор около одной единицы: при отрисовке он
 *   превращается в тонкую щель цветом подложки и разделяет мышцы без обводки.
 *
 * Незакрашенные места (голова, шея, кисти, стопы, колени, таз спереди) — намеренно: для них
 * нет значения в [Muscle], и тап по ним ничего не выбирает.
 */
object BodyGeometry {

    const val WIDTH: Float = 100f
    const val HEIGHT: Float = 220f

    /**
     * Половина контура корпуса сверху вниз: темя → плечо → подмышка → бок → нога → пах.
     * Крайние точки лежат на оси симметрии и при зеркалировании не дублируются.
     */
    private val TORSO_HALF: String =
        // голова и шея
        "50 5 55.8 7.5 58 15 57 22.5 54.2 29 53.4 33 " +
            // трапеция и плечо
            "57.5 36.5 64.5 39.5 71 43.5 " +
            // дельта: наружу и обратно внутрь под плечевой сустав
            "76 48.5 78.5 55.5 77.5 62 73 65.5 69 64.5 66 62 " +
            // бок: рёбра, талия, таз
            "65.2 69 63.4 79 61 88 61.8 96 64.8 104 66.8 112 66.5 120 " +
            // наружная сторона ноги
            "65.5 130 63 143 60.8 154 59.6 163 61 173 58 188 55.8 198 " +
            // стопа
            "57.8 206 58.2 212 51.5 213 " +
            // внутренняя сторона ноги вверх до паха
            "51 200 52 186 52.8 170 52.2 158 52 145 51.4 130 51 120 50 116"

    /**
     * Рука отдельной фигурой: сверху она уходит под дельту (корпус рисуется поверх и прячет стык),
     * а от подмышки и ниже между рукой и боком остаётся настоящий просвет. Одним контуром такой
     * просвет не получается — он вырождается в щель толщиной в обводку, и рука выглядит приросшей.
     */
    private val ARM: String =
        // край под дельтой
        "67 58 73 55 77 58 " +
            // наружная сторона до запястья
            "78 64 76.5 76 74.5 88 73 98 71.5 109 70 119 " +
            // кисть
            "71.8 125 70.5 134 65.5 137 " +
            // внутренняя сторона вверх до подмышки
            "64.5 128 63 118 65 107 67.5 96 69.5 86 69.5 74 68.5 64"

    /**
     * Части силуэта в порядке отрисовки: сначала руки, поверх — корпус. Спереди и сзади силуэт
     * один и тот же, поэтому фигуры стоят рядом одинаковыми.
     */
    val silhouette: List<BodyShape> by lazy {
        val arm = BodyShape.smooth(ARM, tension = 0.7f)
        listOf(arm, arm.mirrored(), BodyShape.smoothSymmetric(TORSO_HALF, tension = 0.75f))
    }

    /** Области мышц вида — в порядке отрисовки и проверки попадания (сверху вниз по телу). */
    fun regions(view: BodyView): List<BodyRegion> = when (view) {
        BodyView.FRONT -> frontRegions
        BodyView.BACK -> backRegions
    }

    /**
     * Мышца в точке нормированных координат или `null`, если рядом её нет.
     *
     * Попадание с допуском [TAP_TOLERANCE]: карта размером с ладонь делает узкие мышцы —
     * приводящие, предплечье — тоньше пальца, и требовать точного попадания значит не давать их
     * выбрать вовсе. В пределах допуска побеждает ближайшая область, поэтому тап в щель между
     * мышцами отдаёт ту, к которой он ближе, а тап по голове, колену или мимо фигуры — `null`,
     * то есть сброс выбора.
     */
    fun muscleAt(view: BodyView, x: Float, y: Float): Muscle? =
        regions(view)
            .map { region -> region to region.shapes.minOf { it.distanceTo(x, y) } }
            .minByOrNull { (_, distance) -> distance }
            ?.takeIf { (_, distance) -> distance <= TAP_TOLERANCE }
            ?.first
            ?.muscle

    /** Допуск попадания: два с половиной процента ширины фигуры, около четырёх dp на телефоне. */
    private const val TAP_TOLERANCE = 2.5f

    // --- Вид спереди -------------------------------------------------------------------------

    private val frontRegions: List<BodyRegion> by lazy {
        listOf(
            paired(Muscle.TRAPS, "51.5 34.8 56 36 61 38.5 66 41.8 64.2 44.6 59.5 42.8 54.5 41 51.5 39.5"),
            paired(Muscle.FRONT_DELTS, DELT_MEDIAL),
            paired(Muscle.SIDE_DELTS, DELT_LATERAL),
            paired(Muscle.CHEST, "51 49.5 57 48.8 62.5 50.5 64.5 55 63.5 61 59 65.5 54 67 51 66.5"),
            // Пресс — четыре пары сегментов: так на карте читается прямая мышца живота,
            // а не одно пятно во весь торс.
            BodyRegion(
                Muscle.ABS,
                ABS_BLOCKS.flatMap { block ->
                    val left = BodyShape.smooth(block, tension = 0.55f)
                    listOf(left, left.mirrored())
                },
            ),
            paired(Muscle.OBLIQUES, "56.6 70.5 60 73 61.4 79 60.2 86 58.8 93 57.2 99 56 95.5 56.4 87.5 56.6 79.5"),
            paired(Muscle.BICEPS, UPPER_ARM),
            paired(Muscle.FOREARMS, FOREARM),
            paired(
                Muscle.QUADS,
                "55.8 119 59 118.5 63.4 122 63.9 131 62.2 142 60.2 152 58 157 56.4 150 55.8 140 55.6 130",
            ),
            paired(Muscle.ADDUCTORS, "51.8 118 55 118.5 54.8 127 54.4 136 53.6 144 52.9 138 52.4 130 52 123"),
            paired(Muscle.CALVES, "54 167 57.2 166.5 58.8 172 58.2 180 56.9 188 55.8 192.5 55 188 54.5 180 54 173"),
        )
    }

    /** Сегменты прямой мышцы живота, левая колонка сверху вниз. */
    private val ABS_BLOCKS: List<String> = listOf(
        "50.9 69.4 53.2 69 55.8 69.6 56 73 55.8 76.4 53.2 77 50.9 76.6 50.8 73",
        "50.9 78.4 53.2 78 55.8 78.6 55.9 82 55.7 85.4 53.2 86 50.9 85.6 50.8 82",
        "50.9 87.4 53.1 87 55.4 87.6 55.6 91 55.3 94.4 53.1 95 50.9 94.6 50.8 91",
        "50.9 96.4 52.9 96 54.8 96.8 54.9 100 54.5 103.4 52.8 104 50.9 103.6 50.8 100",
    )

    // --- Вид сзади ---------------------------------------------------------------------------

    private val backRegions: List<BodyRegion> by lazy {
        listOf(
            // Трапеция сзади — «крыло» от шеи к плечу и вниз по позвоночнику.
            paired(
                Muscle.TRAPS,
                "50.8 34.5 55.5 35.6 61.5 38.6 65.5 41.6 63.4 44.8 59.8 46.5 56.6 53.5 54.5 63.5 52.6 72 50.8 78",
                tension = 0.7f,
            ),
            paired(Muscle.REAR_DELTS, DELT_MEDIAL),
            paired(Muscle.SIDE_DELTS, DELT_LATERAL),
            paired(Muscle.UPPER_BACK, "58 54.5 62.5 56.5 63.8 62 62.8 68.5 60.3 72.5 58.4 68.5 58 62"),
            paired(
                Muscle.LATS,
                "57.4 78 62.4 73.5 62.4 80 60.4 87 59 93.5 57.2 99 56.2 94.5 56.4 88 56.8 82",
                tension = 0.8f,
            ),
            paired(Muscle.LOWER_BACK, "50.8 82 53.8 83.5 55 90 54.4 97.5 52.8 103 51.2 100.5 50.8 92"),
            paired(Muscle.TRICEPS, UPPER_ARM),
            paired(Muscle.FOREARMS, FOREARM),
            paired(Muscle.GLUTES, "51 105 57.2 103.5 63 106.5 65.6 112.5 64.6 120.5 60.4 126 55 127 51.4 121.5"),
            paired(Muscle.HAMSTRINGS, "52.8 131 57.8 129.5 63 132.5 62.2 141.5 60.2 151 58.4 157 56.4 158 54.2 151 53.2 140"),
            // Икра сзади — две головки: на карте это единственное место, где пучки одной мышцы
            // разделены, и именно так её рисуют в атласах.
            BodyRegion(
                Muscle.CALVES,
                listOf(CALF_MEDIAL, CALF_LATERAL).flatMap { points ->
                    val left = BodyShape.smooth(points)
                    listOf(left, left.mirrored())
                },
            ),
        )
    }

    private const val CALF_MEDIAL = "53.9 167.5 56 166.5 56.6 172.5 56.4 180 55.4 187 54.4 190.5 53.9 182 53.7 174"
    private const val CALF_LATERAL =
        "57.6 167 59 169 59.2 175.5 58.3 182 57.3 188 56.6 189.5 57.2 181 57.4 173"

    /** Передняя и задняя дельта лежат одинаково — разными их делают только соседи по виду. */
    private const val DELT_MEDIAL = "65.2 46.2 69.8 47.8 72 52 72 58.5 70 63 67.5 60.5 66.8 55 66 50"
    private const val DELT_LATERAL = "69 44 74 47 76.8 53 76.8 60 74 63.8 71.5 62.5 72.8 57.5 72.5 51"

    /** Плечо: спереди это бицепс, сзади — трицепс, и занимают они одно и то же место. */
    private const val UPPER_ARM =
        "70.8 64.5 73.5 65.5 76 70 75.8 76.5 74.5 83 72.8 87 71.2 83 70.6 76 70.6 70"

    /** Предплечье одинаково на обоих видах: с этого ракурса разницы всё равно не видно. */
    private const val FOREARM =
        "68.6 94 71.2 94.5 72 100 71.2 108 69.8 116 68.2 121 66.4 116 66.6 108 67.4 100"

    /** Мышца из одной фигуры: левая задаётся точками, правая получается зеркально. */
    private fun paired(muscle: Muscle, points: String, tension: Float = 1f): BodyRegion {
        val left = BodyShape.smooth(points, tension)
        return BodyRegion(muscle, listOf(left, left.mirrored()))
    }
}
